import { Injectable } from '@nestjs/common';

import { PrismaService } from '../prisma/prisma.service';

@Injectable()
export class WebsitePackagesRepository {
  constructor(private readonly prisma: PrismaService) {}

  findPropertyTypeActive(propertyTypeId: string) {
    return this.prisma.propertyType.findFirst({
      where: { id: propertyTypeId, isActive: true },
      select: { id: true, serviceId: true },
    });
  }

  findAllActiveForPropertyType(propertyTypeId: string) {
    return this.prisma.package.findMany({
      where: { propertyTypeId, isActive: true },
      select: {
        id: true,
        name: true,
        description: true,
        durationMinutes: true,
        displayOrder: true,
        pricingOptions: {
          where: { isActive: true },
          select: { id: true, label: true, price: true, displayOrder: true },
          orderBy: [{ displayOrder: 'asc' }, { label: 'asc' }],
        },
      },
      orderBy: [{ displayOrder: 'asc' }, { name: 'asc' }],
    });
  }
}
