import { BadRequestException, Injectable, Logger, NotFoundException } from '@nestjs/common';

import { WebsitePackageQueryDto } from './dto/website-package-query.dto';
import { WebsitePackagesRepository } from './website-packages.repository';

@Injectable()
export class WebsitePackagesService {
  private readonly logger = new Logger(WebsitePackagesService.name);

  constructor(private readonly websitePackagesRepository: WebsitePackagesRepository) {}

  async getPackages(query: WebsitePackageQueryDto) {
    this.logger.log(`GET /website/packages?serviceId=${query.serviceId}&propertyTypeId=${query.propertyTypeId}`);

    const propertyType = await this.websitePackagesRepository.findPropertyTypeActive(query.propertyTypeId);
    if (!propertyType) throw new NotFoundException('Property type not found');
    if (propertyType.serviceId !== query.serviceId) {
      throw new BadRequestException('Property type does not belong to the selected service');
    }

    const packages = await this.websitePackagesRepository.findAllActiveForPropertyType(query.propertyTypeId);
    const data = packages.map((pkg) => ({
      id: pkg.id,
      name: pkg.name,
      description: pkg.description,
      durationMinutes: pkg.durationMinutes,
      displayOrder: pkg.displayOrder,
      pricingOptions: pkg.pricingOptions,
    }));

    return { success: true, message: 'Packages fetched successfully', data };
  }
}
