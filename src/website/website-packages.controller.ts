import { Controller, Get, Query } from '@nestjs/common';
import { ApiOperation, ApiResponse, ApiTags } from '@nestjs/swagger';

import { WebsitePackageQueryDto } from './dto/website-package-query.dto';
import { WebsitePackagesService } from './website-packages.service';

// Website-only. There is no bare `/packages` route consumed by the Mobile App today — the
// Mobile App reaches packages via `/property-types/:propertyTypeId/packages` — so this is a
// net-new path, kept under /website for namespace consistency with the rest of Module 2.
@ApiTags('Website / Services')
@Controller('website/packages')
export class WebsitePackagesController {
  constructor(private readonly websitePackagesService: WebsitePackagesService) {}

  @Get()
  @ApiOperation({ summary: 'List active packages (with their pricing options) for a property type — website' })
  @ApiResponse({
    status: 200,
    description: 'Active package list',
    schema: {
      example: {
        success: true,
        message: 'Packages fetched successfully',
        data: [{
          id: 'uuid', name: 'Basic Clean', description: '...', durationMinutes: 90, displayOrder: 0,
          pricingOptions: [{ id: 'uuid', label: '1 Unit', price: 399, displayOrder: 0 }],
        }],
      },
    },
  })
  @ApiResponse({ status: 400, description: 'Validation error — serviceId/propertyTypeId required, or propertyType does not belong to serviceId' })
  @ApiResponse({ status: 404, description: 'Property type not found' })
  getPackages(@Query() query: WebsitePackageQueryDto) {
    return this.websitePackagesService.getPackages(query);
  }
}
